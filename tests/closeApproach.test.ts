import { describe, expect, it } from 'vitest';
import { bCrit, closeApproach, goldenMin, impactCategory, impactEnergy, sphereMass } from '../src/physics/closeApproach';
import { AU, MU_HOME, MU_SUN, R_HOME, YEAR } from '../src/physics/constants';
import { stateToElements } from '../src/physics/elements';
import { propagate, type Elements } from '../src/physics/kepler';
import vectors from './vectors/closeApproach.json';

const HOME: Elements = { a: AU, e: 0.017, w: 0.3, M0: 1.1, t0: 0 };

describe('closeApproach', () => {
  it('FOCUSING: v_inf = 10 km/s gives b_crit ≈ 1.50 R_home', () => {
    expect(bCrit(MU_HOME, R_HOME, 10e3) / R_HOME).toBeCloseTo(1.5, 1);
    expect(bCrit(MU_HOME, R_HOME, 1e9) / R_HOME).toBeCloseTo(1, 6); // no focusing at infinite speed
  });

  it('goldenMin finds the minimum of a parabola', () => {
    expect(goldenMin((t) => (t - 3.3) ** 2, 0, 10, 1e-9)).toBeCloseTo(3.3, 8);
  });

  it('a constructed collision impacts with d_min ≈ 0 at t_i', () => {
    const tI = 5 * YEAR;
    const hs = propagate(HOME, MU_SUN, tI);
    const el = stateToElements(hs.r, { x: hs.v.x + 12e3 * Math.cos(1), y: hs.v.y + 12e3 * Math.sin(1) }, MU_SUN, tI);
    const ca = closeApproach(el, HOME, MU_SUN, MU_HOME, R_HOME, tI);
    expect(ca.impact).toBe(true);
    expect(ca.dMin).toBeLessThan(1e5);
    expect(Math.abs(ca.tCa - tI)).toBeLessThan(5);
    expect(ca.vInf / 12e3).toBeCloseTo(1, 6);
    expect(ca.vImpact).toBeGreaterThan(ca.vInf);
    expect(ca.marginRadii).toBeLessThan(0);
  });

  it('a nudged orbit misses by the expected amount (3 dv T rule, order of magnitude)', () => {
    const tI = 5 * YEAR;
    const hs = propagate(HOME, MU_SUN, tI);
    const el = stateToElements(hs.r, { x: hs.v.x + 12e3 * Math.cos(1), y: hs.v.y + 12e3 * Math.sin(1) }, MU_SUN, tI);
    // Along-track dv of 1 m/s applied 4 years before impact should move d_min by roughly 3 * 1 * 4 yr ≈ 3.8e8 m.
    const t0 = tI - 4 * YEAR;
    const s0 = propagate(el, MU_SUN, t0);
    const vm = Math.hypot(s0.v.x, s0.v.y);
    const el2 = stateToElements(s0.r, { x: s0.v.x + s0.v.x / vm, y: s0.v.y + s0.v.y / vm }, MU_SUN, t0);
    const ca = closeApproach(el2, HOME, MU_SUN, MU_HOME, R_HOME, tI);
    expect(ca.dMin).toBeGreaterThan(1e8);
    expect(ca.dMin).toBeLessThan(1e9);
    expect(ca.impact).toBe(false);
  });

  it('energy and category', () => {
    expect(sphereMass(100, 2700) / 1.41e9).toBeCloseTo(1, 1);
    const e = impactEnergy(100, 2700, 20e3);
    expect(e.energyMt).toBeGreaterThan(60);
    expect(e.energyMt).toBeLessThan(75);
    expect(impactCategory(20)).toBe('AIRBURST');
    expect(impactCategory(20, true)).toBe('CITY');
    expect(impactCategory(500)).toBe('REGIONAL');
    expect(impactCategory(1000)).toBe('GLOBAL');
  });
});

describe('shared vectors (generated by pymiss)', () => {
  interface Vec {
    closeApproach: { threat: Elements; home: Elements; tNominal: number; tCa: number; dMin: number; vInf: number; bCrit: number; impact: boolean }[];
    bCrit: { vInf: number; bCrit: number }[];
    energy: { D: number; rho: number; v: number; Mt: number }[];
  }
  const vec = vectors as Vec;
  it('closeApproach agrees with Python', () => {
    expect(vec.closeApproach.length).toBeGreaterThan(5);
    for (const c of vec.closeApproach) {
      const ca = closeApproach(c.threat, c.home, MU_SUN, MU_HOME, R_HOME, c.tNominal);
      expect(Math.abs(ca.tCa - c.tCa)).toBeLessThan(3);
      expect(ca.dMin).toBeCloseTo(c.dMin, -1); // within 10 m
      expect(ca.vInf / c.vInf).toBeCloseTo(1, 9);
      expect(ca.bCrit / c.bCrit).toBeCloseTo(1, 9);
      expect(ca.impact).toBe(c.impact);
    }
  });
  it('bCrit and energy agree with Python', () => {
    for (const c of vec.bCrit) expect(bCrit(MU_HOME, R_HOME, c.vInf) / c.bCrit).toBeCloseTo(1, 12);
    for (const c of vec.energy) expect(impactEnergy(c.D, c.rho, c.v).energyMt / c.Mt).toBeCloseTo(1, 12);
  });
});
