import { describe, expect, it } from 'vitest';
import vectors from './vectors/kepler.json';
import { AU, DAY, MU_SUN } from '../src/physics/constants';
import { OrbitError, stateToElements } from '../src/physics/elements';
import { orbitPoints, period, propagate, solveKepler, specificEnergy, visViva, type Elements } from '../src/physics/kepler';
import { Rng } from '../src/sim/rng';

const HOME: Elements = { a: AU, e: 0.017, w: 0.3, M0: 1.1, t0: 0 };

describe('kepler', () => {
  it('KEPLER: HOME period is 365.25 d within 0.01 d and r at periapsis is a(1-e)', () => {
    expect(period(MU_SUN, AU) / DAY).toBeCloseTo(365.25, 1);
    expect(Math.abs(period(MU_SUN, AU) / DAY - 365.25)).toBeLessThan(0.01);
    const tp = -(HOME.M0 / Math.sqrt(MU_SUN / AU ** 3)); // time when M = 0 (periapsis)
    const s = propagate(HOME, MU_SUN, tp);
    expect(Math.hypot(s.r.x, s.r.y) / AU).toBeCloseTo(1 - 0.017, 9);
  });

  it('solveKepler matches the classic check value and handles high e', () => {
    expect(solveKepler(1, 0.5)).toBeCloseTo(1.49870113351785, 11);
    for (const e of [0, 0.3, 0.8, 0.95, 0.99]) {
      for (let M = 0; M < 2 * Math.PI; M += 0.37) {
        const E = solveKepler(M, e);
        expect(E - e * Math.sin(E)).toBeCloseTo(M % (2 * Math.PI), 10);
      }
    }
  });

  it('circular orbit at 1 AU moves at 29.78 km/s and returns after one period', () => {
    const el: Elements = { a: AU, e: 0, w: 0, M0: 0, t0: 0 };
    const s0 = propagate(el, MU_SUN, 0);
    expect(s0.r.x / AU).toBeCloseTo(1, 12);
    expect(s0.v.y / 1000).toBeCloseTo(29.78, 1);
    expect(visViva(MU_SUN, AU, AU) / 1000).toBeCloseTo(29.78, 1);
    const s1 = propagate(el, MU_SUN, period(MU_SUN, AU));
    expect(s1.r.x / AU).toBeCloseTo(1, 9);
    expect(Math.abs(s1.r.y) / AU).toBeLessThan(1e-9);
  });

  it('ENERGY: specific energy constant to 1e-12 relative over one orbit', () => {
    const el: Elements = { a: 1.3 * AU, e: 0.6, w: 2.0, M0: 0.4, t0: 0 };
    const eps0 = -MU_SUN / (2 * el.a);
    const T = period(MU_SUN, el.a);
    for (let i = 0; i <= 400; i++) {
      const s = propagate(el, MU_SUN, (i / 400) * T);
      const eps = specificEnergy(MU_SUN, Math.hypot(s.r.x, s.r.y), Math.hypot(s.v.x, s.v.y));
      expect(Math.abs((eps - eps0) / eps0)).toBeLessThan(1e-12);
    }
  });

  it('ROUNDTRIP: state -> elements -> state within 1 m and 1e-6 m/s', () => {
    const rng = new Rng(2026);
    for (let i = 0; i < 200; i++) {
      const el: Elements = { a: rng.float(0.3, 6) * AU, e: rng.float(0, 0.95), w: rng.float(0, 2 * Math.PI), M0: rng.float(0, 2 * Math.PI), t0: rng.float(0, 1e9) };
      const t = el.t0 + rng.float(0, 1e9);
      const s = propagate(el, MU_SUN, t);
      const back = stateToElements(s.r, s.v, MU_SUN, t);
      const s2 = propagate(back, MU_SUN, t);
      expect(Math.hypot(s2.r.x - s.r.x, s2.r.y - s.r.y)).toBeLessThan(1);
      expect(Math.hypot(s2.v.x - s.v.x, s2.v.y - s.v.y)).toBeLessThan(1e-6);
      expect(back.a / el.a).toBeCloseTo(1, 9);
      expect(back.e).toBeCloseTo(el.e, 9);
    }
  });

  it('stateToElements rejects retrograde and unbound states, handles circular', () => {
    expect(() => stateToElements({ x: AU, y: 0 }, { x: 0, y: -29780 }, MU_SUN, 0)).toThrow(OrbitError);
    expect(() => stateToElements({ x: AU, y: 0 }, { x: 0, y: 60000 }, MU_SUN, 0)).toThrow(/unbound/);
    const el = stateToElements({ x: AU, y: 0 }, { x: 0, y: visViva(MU_SUN, AU, AU) }, MU_SUN, 0);
    expect(el.e).toBe(0);
    expect(el.w).toBe(0);
    expect(el.M0).toBeCloseTo(0, 9);
  });

  it('orbitPoints traces r(nu) between periapsis and apoapsis', () => {
    const pts = orbitPoints(HOME, 64);
    let rmin = Infinity;
    let rmax = 0;
    for (let i = 0; i < pts.length; i += 2) {
      const r = Math.hypot(pts[i] as number, pts[i + 1] as number);
      rmin = Math.min(rmin, r);
      rmax = Math.max(rmax, r);
    }
    expect(rmin / AU).toBeCloseTo(1 - 0.017, 6);
    expect(rmax / AU).toBeCloseTo(1 + 0.017, 3);
  });
});

describe('shared vectors (generated by pymiss)', () => {
  interface KeplerVectors {
    solveKepler: { M: number; e: number; E: number }[];
    propagate: { a: number; e: number; w: number; M0: number; t0: number; mu: number; t: number; x: number; y: number; vx: number; vy: number }[];
    stateToElements: { x: number; y: number; vx: number; vy: number; mu: number; t: number; a: number; e: number; w: number; M0: number }[];
  }
  const vec = vectors as KeplerVectors;

  it('solveKepler agrees with Python', () => {
    expect(vec.solveKepler.length).toBeGreaterThan(10);
    for (const c of vec.solveKepler) expect(solveKepler(c.M, c.e)).toBeCloseTo(c.E, 11);
  });
  it('propagate agrees with Python to 1e-9 relative', () => {
    for (const c of vec.propagate) {
      const s = propagate({ a: c.a, e: c.e, w: c.w, M0: c.M0, t0: c.t0 }, c.mu, c.t);
      const scale = Math.hypot(c.x, c.y);
      expect(Math.hypot(s.r.x - c.x, s.r.y - c.y) / scale).toBeLessThan(1e-9);
      expect(Math.hypot(s.v.x - c.vx, s.v.y - c.vy) / Math.hypot(c.vx, c.vy)).toBeLessThan(1e-9);
    }
  });
  it('stateToElements agrees with Python', () => {
    for (const c of vec.stateToElements) {
      const el = stateToElements({ x: c.x, y: c.y }, { x: c.vx, y: c.vy }, c.mu, c.t);
      expect(el.a / c.a).toBeCloseTo(1, 9);
      expect(el.e).toBeCloseTo(c.e, 9);
      expect(el.w).toBeCloseTo(c.w, 8);
      expect(el.M0).toBeCloseTo(c.M0, 8);
    }
  });
});
