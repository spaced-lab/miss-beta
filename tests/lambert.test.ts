import { describe, expect, it } from 'vitest';
import { AU, DAY, MU_SUN, YEAR } from '../src/physics/constants';
import { stateToElements } from '../src/physics/elements';
import { c3FromVinf, launcherTier, missFromImpulse, missFromPush, payloadForC3 } from '../src/physics/estimates';
import { propagate, visViva } from '../src/physics/kepler';
import { alongTrack, kineticDv, kineticImpact } from '../src/physics/kinetic';
import { lambert } from '../src/physics/lambert';
import { stumpffC, stumpffS } from '../src/physics/stumpff';
import vectors from './vectors/lambert.json';

describe('stumpff', () => {
  it('has the right limits and values', () => {
    expect(stumpffS(0)).toBeCloseTo(1 / 6, 15);
    expect(stumpffC(0)).toBeCloseTo(1 / 2, 15);
    expect(stumpffS(1)).toBeCloseTo(0.1585290151921035, 12);
    expect(stumpffC(1)).toBeCloseTo(0.4596976941318602, 12);
    expect(stumpffS(-1)).toBeCloseTo((Math.sinh(1) - 1) / 1, 12);
    // Continuity across the series switch: closed form just outside the window equals the series there.
    for (const z of [1.1e-3, -1.1e-3]) {
      expect(stumpffS(z)).toBeCloseTo(1 / 6 - z / 120 + (z * z) / 5040 - (z * z * z) / 362880, 12);
      expect(stumpffC(z)).toBeCloseTo(1 / 2 - z / 24 + (z * z) / 720 - (z * z * z) / 40320, 12);
    }
  });
});

describe('lambert', () => {
  it('LAMBERT: near-Hohmann 1.0 -> 1.524 AU in 259 d gives dep v_inf ≈ 2.94 and arr ≈ 2.65 km/s within 2%', () => {
    const th = (177 * Math.PI) / 180;
    const res = lambert({ x: AU, y: 0 }, { x: 1.524 * AU * Math.cos(th), y: 1.524 * AU * Math.sin(th) }, 259 * DAY, MU_SUN);
    expect(res).not.toBeNull();
    if (!res) return;
    const vc1 = visViva(MU_SUN, AU, AU);
    const vc2 = visViva(MU_SUN, 1.524 * AU, 1.524 * AU);
    expect(Math.abs((Math.hypot(res.v1.x, res.v1.y) - vc1) / 2940 - 1)).toBeLessThan(0.02);
    expect(Math.abs((vc2 - Math.hypot(res.v2.x, res.v2.y)) / 2650 - 1)).toBeLessThan(0.02);
    expect(res.a / AU).toBeCloseTo(1.262, 2);
    expect(c3FromVinf(2940)).toBeCloseTo(8.64, 2);
  });

  it('the transfer actually lands on the target (propagation check)', () => {
    for (const [r2au, ang, days] of [[2.0, 2.0, 300], [0.72, 4.0, 150], [1.1, 1.0, 120], [5.2, 2.5, 800]] as const) {
      const r1 = { x: AU, y: 0 };
      const r2 = { x: r2au * AU * Math.cos(ang), y: r2au * AU * Math.sin(ang) };
      const dt = days * DAY;
      const res = lambert(r1, r2, dt, MU_SUN);
      expect(res).not.toBeNull();
      if (!res) continue;
      const el = stateToElements(r1, res.v1, MU_SUN, 0);
      const s = propagate(el, MU_SUN, dt);
      expect(Math.hypot(s.r.x - r2.x, s.r.y - r2.y)).toBeLessThan(1000);
      expect(Math.hypot(s.v.x - res.v2.x, s.v.y - res.v2.y)).toBeLessThan(1e-3);
    }
  });

  it('returns null for degenerate geometry and impossible times', () => {
    expect(lambert({ x: AU, y: 0 }, { x: -AU, y: 0 }, 100 * DAY, MU_SUN)).toBeNull();
    expect(lambert({ x: AU, y: 0 }, { x: 2 * AU, y: 0 }, 100 * DAY, MU_SUN)).toBeNull();
    expect(lambert({ x: AU, y: 0 }, { x: 0, y: AU }, 0, MU_SUN)).toBeNull();
  });
});

describe('kinetic', () => {
  it('DART: 580 kg at 6.14 km/s on 4.3e9 kg with beta 3.6 gives ≈ 3.0 mm/s', () => {
    const dv = kineticDv(580, 4.3e9, 6140, 3.6);
    expect(dv / 2.98e-3).toBeCloseTo(1, 2);
    expect(Math.abs(dv / 2.7e-3 - 1)).toBeLessThan(0.5); // within 50% of the observed 2.7 mm/s
    const r = kineticImpact(580, 4.3e9, { x: 6140, y: 0 }, { x: 0, y: 0 }, 3.6);
    expect(r.U).toBe(6140);
    expect(r.dv.x).toBeCloseTo(dv, 12);
    expect(r.Q).toBeCloseTo((0.5 * 580 * 6140 * 6140) / 4.3e9, 9);
    expect(alongTrack({ x: 1, y: 1 }, { x: 1, y: 0 })).toBe(1);
  });
});

describe('estimates', () => {
  it('3 dv T: 1 cm/s with 10 years left is about 9.5e6 m (1.5 R)', () => {
    expect(missFromImpulse(0.01, 10 * YEAR) / 9.47e6).toBeCloseTo(1, 2);
    expect(missFromPush(1e-9, YEAR, 2 * YEAR)).toBeCloseTo(3 * 1e-9 * YEAR * 2.5 * YEAR, 6);
  });
  it('payload tables interpolate in log(mass) and fade to zero', () => {
    const t1 = launcherTier(1);
    expect(payloadForC3(t1, 0)).toBe(4000);
    expect(payloadForC3(t1, 10)).toBeCloseTo(Math.sqrt(4000 * 2000), 6);
    expect(payloadForC3(t1, 70)).toBeCloseTo(150, 6);
    expect(payloadForC3(t1, 80)).toBe(0);
    expect(payloadForC3(launcherTier(3), 130)).toBeCloseTo(1000, 9);
    expect(payloadForC3(launcherTier(3), 131)).toBe(0);
    expect(() => launcherTier(9)).toThrow();
  });
});

describe('shared vectors (generated by pymiss)', () => {
  interface Vec {
    stumpff: { z: number; S: number; C: number }[];
    lambert: { r1x: number; r1y: number; r2x: number; r2y: number; dt: number; mu: number; v1x: number; v1y: number; v2x: number; v2y: number; z: number; dtheta: number }[];
    kinetic: { m: number; M: number; vix: number; viy: number; vtx: number; vty: number; beta: number; dvx: number; dvy: number; U: number; Q: number }[];
    estimates: { impulse: { dv: number; T: number; miss: number }[]; push: { a: number; tau: number; tRem: number; miss: number }[]; payload: { tier: number; c3: number; kg: number }[] };
  }
  const vec = vectors as Vec;
  it('stumpff agrees', () => {
    for (const c of vec.stumpff) {
      expect(stumpffS(c.z)).toBeCloseTo(c.S, 12);
      expect(stumpffC(c.z)).toBeCloseTo(c.C, 12);
    }
  });
  it('lambert agrees to 1e-9 relative on 30 random transfers and 7 fast hyperbolic ones', () => {
    expect(vec.lambert.length).toBe(37);
    for (const c of vec.lambert) {
      const res = lambert({ x: c.r1x, y: c.r1y }, { x: c.r2x, y: c.r2y }, c.dt, c.mu);
      expect(res).not.toBeNull();
      if (!res) continue;
      expect(Math.hypot(res.v1.x - c.v1x, res.v1.y - c.v1y) / Math.hypot(c.v1x, c.v1y)).toBeLessThan(1e-9);
      expect(Math.hypot(res.v2.x - c.v2x, res.v2.y - c.v2y) / Math.hypot(c.v2x, c.v2y)).toBeLessThan(1e-9);
      expect(res.dtheta).toBeCloseTo(c.dtheta, 12);
    }
  });
  it('kinetic and estimates agree', () => {
    for (const c of vec.kinetic) {
      const r = kineticImpact(c.m, c.M, { x: c.vix, y: c.viy }, { x: c.vtx, y: c.vty }, c.beta);
      expect(r.dv.x).toBeCloseTo(c.dvx, 12);
      expect(r.dv.y).toBeCloseTo(c.dvy, 12);
      expect(r.U).toBeCloseTo(c.U, 9);
      expect(r.Q / c.Q).toBeCloseTo(1, 12);
    }
    for (const c of vec.estimates.impulse) expect(missFromImpulse(c.dv, c.T)).toBeCloseTo(c.miss, 6);
    for (const c of vec.estimates.push) expect(missFromPush(c.a, c.tau, c.tRem) / c.miss).toBeCloseTo(1, 12);
    for (const c of vec.estimates.payload) expect(payloadForC3(launcherTier(c.tier), c.c3)).toBeCloseTo(c.kg, 6);
  });
});
