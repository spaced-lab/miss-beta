import { describe, expect, it } from 'vitest';
import { diameterFromMass, disrupt, escapeSpeedBody, f3D, fragmentMasses, harmlessDiameter, largestRemnantFraction, qStar, specificEnergy } from '../src/physics/fragment';
import { Rng } from '../src/sim/rng';
import vectors from './vectors/fragment.json';

describe('fragment physics', () => {
  it('Q_STAR: basalt R = 100 m, rho 2700 gives 300..400 J/kg; the sanity ladder holds', () => {
    expect(qStar(100, 2700)).toBeGreaterThan(300);
    expect(qStar(100, 2700)).toBeLessThan(400);
    expect(qStar(500, 2700)).toBeGreaterThan(400);
    expect(qStar(500, 2700)).toBeLessThan(650);
    expect(qStar(5000, 2700)).toBeGreaterThan(5000);
    expect(qStar(5000, 2700)).toBeLessThan(10000);
    expect(qStar(100, 2700, 5)).toBeCloseTo(5 * qStar(100, 2700), 9); // iron strength multiplier
    expect(qStar(300, 600, 0.3, 'ice')).toBeLessThan(qStar(300, 600, 0.3, 'basalt'));
  });

  it('largest remnant and helpers', () => {
    expect(largestRemnantFraction(100, 400)).toBe(0.5);
    expect(largestRemnantFraction(800, 400)).toBeCloseTo(0.02, 12);
    expect(largestRemnantFraction(600, 400)).toBeCloseTo(0.25, 12);
    expect(diameterFromMass((4 / 3) * Math.PI * 50 ** 3 * 2700, 2700)).toBeCloseTo(100, 9);
    expect(escapeSpeedBody(1.4e9, 50)).toBeCloseTo(0.0611, 3);
    expect(specificEnergy(1500, 1.4e9, 10000)).toBeCloseTo(53.57, 1);
    expect(harmlessDiameter(false)).toBe(25);
    expect(harmlessDiameter(true)).toBe(10);
    expect(f3D(9.5e6, 0.01, 3e8)).toBe(1);
    expect(f3D(9.5e6, 1, 3e8)).toBeCloseTo(9.5e6 / (0.6 * 3e8), 9);
  });

  it('FRAGMENT: masses sum to the parent within 1e-9 and momentum is conserved within 1e-6', () => {
    const M = 1.4e9;
    const R = 50;
    const rho = 2700;
    const m = 20000;
    const Uvec = { x: 12000, y: 0 };
    const Q = specificEnergy(m, M, 12000);
    const Qs = qStar(R, rho);
    expect(Q).toBeGreaterThan(Qs);
    const frags = disrupt(new Rng(9), { M, R, rho, Q, Qstar: Qs, m, Uvec, vThreat: { x: 30000, y: 0 }, nFrag: 15 });
    expect(frags.length).toBe(16);
    const total = frags.reduce((a, f) => a + f.mass, 0);
    expect(Math.abs(total - M) / M).toBeLessThan(1e-9);
    const px = frags.reduce((a, f) => a + f.mass * f.v.x, 0);
    const py = frags.reduce((a, f) => a + f.mass * f.v.y, 0);
    expect(Math.abs(px - (M * 30000 + m * Uvec.x)) / (M * 30000)).toBeLessThan(1e-6);
    expect(Math.abs(py - m * Uvec.y) / (M * 30000)).toBeLessThan(1e-6);
    expect(frags[0]?.largestRemnant).toBe(true);
    // NOTE: at Q/Q* well above 2 the linear f_LR saturates at 0.02, so the 'largest remnant' can be smaller than a Pareto piece.
    expect(frags[0]?.mass).toBeCloseTo(largestRemnantFraction(Q, Qs) * M, 3);
    const ms = fragmentMasses(new Rng(3), 1e9, 20);
    expect(Math.abs(ms.reduce((a, b) => a + b, 0) - 1e9) / 1e9).toBeLessThan(1e-12);
  });

  it('ejection speeds scale with sqrt(Q/Q*)', () => {
    const base = { M: 1.4e9, R: 50, rho: 2700, m: 20000, Uvec: { x: 12000, y: 0 }, vThreat: { x: 0, y: 0 }, nFrag: 30 };
    const Qs = qStar(50, 2700);
    const kcom = base.m / (base.M + base.m);
    const spread = (Q: number) => {
      const fr = disrupt(new Rng(5), { ...base, Q, Qstar: Qs });
      // Remove the common centre-of-mass push; what is left is the ejection field, which scales with sqrt(Q/Q*).
      return Math.sqrt(fr.reduce((a, f) => a + (f.v.x - kcom * 12000) ** 2 + f.v.y ** 2, 0) / fr.length);
    };
    const ratio = spread(4 * Qs) / spread(Qs);
    expect(ratio).toBeGreaterThan(1.8);
    expect(ratio).toBeLessThan(2.2);
  });
});

describe('shared vectors (generated by pymiss)', () => {
  interface Vec {
    qStar: { R: number; rho: number; mult: number; material: 'basalt' | 'ice'; Qstar: number }[];
    largestRemnant: { Q: number; Qs: number; f: number }[];
    masses: { seed: number; total: number; n: number; masses: number[] };
    disrupt: { seed: number; M: number; R: number; rho: number; Q: number; Qstar: number; m: number; ux: number; uy: number; vtx: number; vty: number; n: number; fragments: { mass: number; D: number; vx: number; vy: number; lr: boolean }[] };
    f3D: { bCrit: number; vEj: number; T: number; f: number }[];
  }
  const vec = vectors as Vec;
  it('agrees with Python bit for bit where the RNG is shared', () => {
    for (const c of vec.qStar) expect(qStar(c.R, c.rho, c.mult, c.material) / c.Qstar).toBeCloseTo(1, 12);
    for (const c of vec.largestRemnant) expect(largestRemnantFraction(c.Q, c.Qs)).toBeCloseTo(c.f, 12);
    const ms = fragmentMasses(new Rng(vec.masses.seed), vec.masses.total, vec.masses.n);
    ms.forEach((v, i) => expect(v / (vec.masses.masses[i] as number)).toBeCloseTo(1, 12));
    const d = vec.disrupt;
    const fr = disrupt(new Rng(d.seed), { M: d.M, R: d.R, rho: d.rho, Q: d.Q, Qstar: d.Qstar, m: d.m, Uvec: { x: d.ux, y: d.uy }, vThreat: { x: d.vtx, y: d.vty }, nFrag: d.n });
    expect(fr.length).toBe(d.fragments.length);
    fr.forEach((f, i) => {
      const e = d.fragments[i];
      if (!e) throw new Error('missing');
      expect(f.mass / e.mass).toBeCloseTo(1, 10);
      expect(f.D / e.D).toBeCloseTo(1, 10);
      expect(f.v.x).toBeCloseTo(e.vx, 6);
      expect(f.v.y).toBeCloseTo(e.vy, 6);
      expect(f.largestRemnant).toBe(e.lr);
    });
    for (const c of vec.f3D) expect(f3D(c.bCrit, c.vEj, c.T)).toBeCloseTo(c.f, 12);
  });
});
